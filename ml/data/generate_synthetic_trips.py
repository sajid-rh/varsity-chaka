"""Synthetic trip dataset generator for Varsity Chaka ETA model.

Generates reproducible synthetic commute data labeled with traffic scenarios across Dhaka.
All data generated by this script is strictly synthetic and labeled as such.
"""
import argparse
from pathlib import Path
import numpy as np
import pandas as pd

DATA_DIR = Path(__file__).resolve().parent


def generate_synthetic_dataset(num_samples: int = 5000, random_seed: int = 42) -> pd.DataFrame:
    """Generate synthetic university commute trips with realistic Dhaka traffic dynamics."""
    rng = np.random.RandomState(random_seed)

    # 1. Distances: typical campus commute in Dhaka ranges between 2.0 km and 32.0 km
    # Log-normal distribution centered around 10-14 km
    raw_dist = rng.lognormal(mean=2.4, sigma=0.45, size=num_samples)
    distance_km = np.clip(raw_dist, 2.0, 32.0)

    # 2. Free-flow car/OSRM base duration: ~35 km/h base free-flow speed
    # ~103 seconds per km with minor random road segment variation
    base_speed_kmh = rng.uniform(32.0, 38.0, size=num_samples)
    osrm_duration_s = np.round((distance_km / base_speed_kmh) * 3600.0).astype(int)

    # 3. Departure timing distributions
    # Bimodal hour distribution with peaks at 08:00 (morning classes) and 17:00 (evening return)
    hours = []
    for _ in range(num_samples):
        r = rng.rand()
        if r < 0.45:
            # Morning rush (7 to 10 AM)
            h = int(rng.normal(loc=8.2, scale=1.0))
        elif r < 0.80:
            # Evening rush (16 to 19 PM)
            h = int(rng.normal(loc=17.5, scale=1.1))
        else:
            # Mid-day or early evening (10 AM to 16 PM, or 19 to 22 PM)
            h = int(rng.uniform(6, 22))
        hours.append(np.clip(h, 0, 23))
    hour_of_day = np.array(hours)

    # Day of week: 0=Mon, 1=Tue, 2=Wed, 3=Thu, 4=Fri, 5=Sat, 6=Sun
    # Uniform across days
    day_of_week = rng.randint(0, 7, size=num_samples)
    # Bangladesh weekend is Friday (4) and Saturday (5)
    is_weekend = np.isin(day_of_week, [4, 5]).astype(int)

    # Peak hour flag
    is_morning_peak = ((hour_of_day >= 7) & (hour_of_day <= 9)).astype(int)
    is_evening_peak = ((hour_of_day >= 16) & (hour_of_day <= 19)).astype(int)
    is_peak_hour = ((is_morning_peak | is_evening_peak) & (is_weekend == 0)).astype(int)

    # 4. Realistic motorcycle actual duration simulation:
    # In Dhaka:
    # - Off-peak motorcycle travel speed: 28-32 km/h (often faster than cars due to size) -> multiplier 0.85 - 1.05 of car base
    # - Peak hour weekday congestion: cars crawl at 8-12 km/h (multiplier 2.5 - 3.5),
    #   while motorcycles filter through jams at 18-22 km/h (multiplier 1.25 - 1.65 of base)
    traffic_multipliers = np.ones(num_samples)

    for i in range(num_samples):
        if is_weekend[i]:
            # Weekend: smooth flow, multiplier 0.85 to 1.10
            traffic_multipliers[i] = rng.uniform(0.85, 1.10)
        elif is_peak_hour[i]:
            # Weekday peak: motorcycle filters through traffic, multiplier 1.25 to 1.60
            # Heavier rush in evening
            mult = rng.normal(loc=1.40, scale=0.12)
            traffic_multipliers[i] = np.clip(mult, 1.15, 1.75)
        else:
            # Weekday off-peak: moderate traffic, multiplier 0.95 to 1.25
            traffic_multipliers[i] = rng.uniform(0.95, 1.25)

    # Noise: Gaussian variance from traffic lights, roadblocks, pedestrian crossings (+- 90s)
    noise_s = rng.normal(loc=0.0, scale=75.0, size=num_samples)
    actual_duration_s = np.round(osrm_duration_s * traffic_multipliers + noise_s).astype(int)
    # Guardrails: actual duration must be at least 120s
    actual_duration_s = np.maximum(actual_duration_s, 120)

    duration_delta_s = actual_duration_s - osrm_duration_s

    df = pd.DataFrame({
        "distance_km": np.round(distance_km, 2),
        "osrm_duration_s": osrm_duration_s,
        "hour_of_day": hour_of_day,
        "day_of_week": day_of_week,
        "is_weekend": is_weekend,
        "is_peak_hour": is_peak_hour,
        "traffic_multiplier": np.round(traffic_multipliers, 3),
        "actual_duration_s": actual_duration_s,
        "duration_delta_s": duration_delta_s,
    })

    return df


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate synthetic ETA dataset")
    parser.add_argument("--samples", type=int, default=5000, help="Number of records")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument("--out", type=str, default=str(DATA_DIR / "synthetic_trips.csv"))
    args = parser.parse_args()

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df_data = generate_synthetic_dataset(num_samples=args.samples, random_seed=args.seed)
    df_data.to_csv(out_path, index=False)
    print(f"Generated {len(df_data)} synthetic trip records -> {out_path}")
